// Generates src/theme/tokens.ts (app) and replica/design/tokens.css (web pages)
// from replica/design/tokens.json. Run: npm run tokens
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const t = JSON.parse(readFileSync(join(root, 'replica/design/tokens.json'), 'utf8'));
const camel = (s) => s.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
const ms = (v) => Number(String(v).replace('ms', ''));

const colors = Object.fromEntries(Object.entries(t.color).map(([k, v]) => [camel(k), v]));
const type = Object.fromEntries(
  Object.entries(t.type).map(([k, v]) => [k, { fontSize: v.size, lineHeight: v.line, fontWeight: String(v.weight) }]),
);
const theme = {
  colors,
  type,
  space: t.space,
  radius: t.radius,
  motion: { fast: ms(t.motion.fast), base: ms(t.motion.base), sheet: ms(t.motion.sheet) },
  layout: t.layout,
};

const header = '// GENERATED by scripts/build-tokens.mjs from replica/design/tokens.json. Do not edit.\n';
writeFileSync(
  join(root, 'src/theme/tokens.ts'),
  `${header}export const tokens = ${JSON.stringify(theme, null, 2)} as const;\n\n` +
    `export type ColorRole = keyof typeof tokens.colors;\nexport type TypeRole = keyof typeof tokens.type;\n`,
);

const css = [
  '/* GENERATED by scripts/build-tokens.mjs. Do not edit. */',
  ':root {',
  ...Object.entries(t.color).map(([k, v]) => `  --color-${k}: ${v};`),
  ...Object.entries(t.type).flatMap(([k, v]) => [
    `  --text-${k}: ${v.size}px;`,
    `  --leading-${k}: ${v.line}px;`,
    `  --weight-${k}: ${v.weight};`,
  ]),
  ...t.space.map((v, i) => `  --space-${i}: ${v}px;`),
  ...Object.entries(t.radius).map(([k, v]) => `  --radius-${k}: ${v}px;`),
  ...Object.entries(t.shadow).map(([k, v]) => `  --shadow-${k}: ${v};`),
  ...Object.entries(t.motion).map(([k, v]) => `  --motion-${k}: ${v};`),
  `  --font-sans: ${t.font.sans}, system-ui, sans-serif;`,
  '}',
  '',
].join('\n');
writeFileSync(join(root, 'replica/design/tokens.css'), css);
console.log('tokens: wrote src/theme/tokens.ts and replica/design/tokens.css');
